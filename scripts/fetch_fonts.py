#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
fetch_fonts.py
--------------
فونت‌های کتاب (Vazirmatn برای فارسی و EB Garamond برای انگلیسی) را از
Google Fonts دانلود می‌کند و به‌صورتِ محلی در assets/fonts/ نگه می‌دارد.

چرا TTF و نه woff2؟ چون کرومیوم هنگام چاپِ PDF فونت‌های woff/woff2 را به
فونتِ Type3 (شکلِ خامِ گلیف‌ها) تبدیل می‌کند: متنِ PDF دیگر قابلِ انتخاب/جست‌وجو
نمی‌شود و حجم فایل بالا می‌رود. با TTF، فونت به‌درستی به‌صورتِ CID جاسازی
می‌شود و لایه‌ی متنِ فارسی/انگلیسی سالم می‌ماند.

فقط وزن‌هایی که در render.py استفاده می‌شوند دانلود می‌شوند تا حجم ریپو کم بماند.

اجرا (فقط وقتی می‌خواهید فونت‌ها را به‌روز کنید):
    python scripts/fetch_fonts.py
"""

import re
import sys
import urllib.request
from pathlib import Path

FONT_DIR = Path(__file__).resolve().parent.parent / "assets" / "fonts"

# فقط وزن‌های لازم: متنِ فارسی/عنوان‌ها + متنِ لاتین/عنوان‌ها/توضیحِ ایتالیک
FAMILIES = [
    ("Vazirmatn", "wght@400;700;800"),
    ("EB+Garamond", "ital,wght@0,400;0,600;1,400"),
]
KEEP = {
    "Vazirmatn": {("normal", "400"), ("normal", "700"), ("normal", "800")},
    "EB Garamond": {("normal", "400"), ("normal", "600"), ("italic", "400")},
}

# UAِ قدیمی → Google Fonts فایلِ TTFِ کامل (بدونِ unicode-range) می‌دهد.
LEGACY_UA = "Mozilla/5.0 (Windows NT 5.1)"


def _get(url: str, binary: bool = False):
    req = urllib.request.Request(url, headers={"User-Agent": LEGACY_UA})
    with urllib.request.urlopen(req, timeout=60) as resp:
        data = resp.read()
    return data if binary else data.decode("utf-8")


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def _css_url() -> str:
    parts = [f"family={name}:{spec}" for name, spec in FAMILIES]
    return "https://fonts.googleapis.com/css2?" + "&".join(parts) + "&display=swap"


def main() -> int:
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    css = _get(_css_url())  # UAِ قدیمی → TTF
    blocks = re.findall(r"@font-face\s*\{(.*?)\}", css, flags=re.S)
    if not blocks:
        print("❌ هیچ @font-face‌ای در پاسخ Google Fonts نبود.")
        return 1

    # فایل‌های قدیمی (مثلاً نسخه‌ی woff2) پاک شوند تا CSS با فایل‌های تازه یکی باشد
    for stale in list(FONT_DIR.glob("*.woff2")) + list(FONT_DIR.glob("*.ttf")):
        stale.unlink()

    rules, saved = [], 0
    for block in blocks:
        family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        style = re.search(r"font-style:\s*(\w+)", block).group(1)
        weight = re.search(r"font-weight:\s*(\d+)", block).group(1)
        if (style, weight) not in KEEP.get(family, set()):
            continue
        src = re.search(r"url\((https://[^)]+)\)", block)
        if not src:
            continue
        url = src.group(1)
        ext = Path(url).suffix or ".ttf"
        name = f"{_slug(family)}-{style}-{weight}{ext}"
        (FONT_DIR / name).write_bytes(_get(url, binary=True))
        saved += 1
        rules.append(
            "@font-face {\n"
            f"  font-family: '{family}';\n"
            f"  font-style: {style};\n"
            f"  font-weight: {weight};\n"
            "  font-display: block;\n"
            f"  src: url('{name}') format('truetype');\n"
            "}"
        )

    header = ("/* vendored from Google Fonts (SIL OFL) — "
              "generated by scripts/fetch_fonts.py */\n")
    (FONT_DIR / "fonts.css").write_text(header + "\n".join(rules) + "\n",
                                        encoding="utf-8")
    total = sum(f.stat().st_size for f in FONT_DIR.glob("*.*")) // 1024
    print(f"✅ {saved} فایل فونت در {FONT_DIR} ذخیره شد ({total} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
